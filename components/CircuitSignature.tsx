"use client";

import { useEffect, useRef, type CSSProperties } from "react";
import { dragoxSignature } from "@/lib/dragox-signature";
import { cn } from "@/lib/utils";

interface CircuitSignatureProps {
  className?: string;
  /** Inline styles, e.g. `{ color }` — lines and dots are drawn in currentColor. */
  style?: CSSProperties;
  /** Seconds before the first letter starts drawing. */
  delay?: number;
  /** Seconds between letters. */
  letterStagger?: number;
}

/**
 * The name drawn from the Dragox Circuit centre lines: each letter's traces draw in,
 * then the junction dots light up. Starts once when scrolled into view.
 * Reduced motion shows the finished drawing (see `.dragox-signature` in globals.css).
 * Path data is generated by scripts/dragox-font/build_font.py.
 */
export function CircuitSignature({
  className,
  style,
  delay = 0.15,
  letterStagger = 0.09,
}: CircuitSignatureProps) {
  const ref = useRef<SVGSVGElement>(null);
  const data = dragoxSignature;

  // Toggle the class on the element directly: starting the CSS animation needs no re-render.
  useEffect(() => {
    const node = ref.current;
    if (!node) return;
    const start = () => node.classList.add("is-drawing");
    if (typeof IntersectionObserver === "undefined") {
      start();
      return;
    }
    const observer = new IntersectionObserver(
      ([entry]) => {
        if (entry?.isIntersecting) {
          start();
          observer.disconnect();
        }
      },
      { threshold: 0.3 },
    );
    observer.observe(node);
    return () => observer.disconnect();
  }, []);

  return (
    <svg
      ref={ref}
      viewBox={`0 0 ${data.width} ${data.height}`}
      role="img"
      aria-label={data.text}
      className={cn("dragox-signature", className)}
      style={style}
    >
      <title>{data.text}</title>
      <g aria-hidden="true" strokeWidth={data.line}>
        {data.glyphs.map((glyph, gi) => {
          const start = delay + gi * letterStagger;
          return (
            <g key={`${glyph.char}-${gi}`}>
              {glyph.paths.map((d, pi) => (
                <path
                  key={pi}
                  d={d}
                  pathLength={1}
                  className="dragox-line"
                  style={{ animationDelay: `${(start + pi * 0.012).toFixed(3)}s` }}
                />
              ))}
              {glyph.dots.map(([cx, cy], di) => (
                <circle
                  key={di}
                  cx={cx}
                  cy={cy}
                  r={data.dot}
                  className="dragox-dot"
                  style={{ animationDelay: `${(start + 0.6 + di * 0.012).toFixed(3)}s` }}
                />
              ))}
            </g>
          );
        })}
      </g>
    </svg>
  );
}
